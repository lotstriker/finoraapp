// Regenerates precache.js — the list of every file the service worker caches for offline use,
// plus a content hash that becomes the cache name (so every deploy refreshes the cache).
// Run:  npm run build:sw      (npm test fails if you forget: tests/pwa.test.mjs)
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const walk = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

export function buildPrecache() {
  const files = [
    'index.html', 'manifest.webmanifest',
    ...walk(join(root, 'css')).map((p) => relative(root, p)),
    ...walk(join(root, 'js')).map((p) => relative(root, p)),
    ...walk(join(root, 'assets')).map((p) => relative(root, p)),
  ].filter((f) => !/(^|\/)\./.test(f)).sort();
  const hash = createHash('sha256');
  for (const f of files) { hash.update(f); hash.update(readFileSync(join(root, f))); }
  const version = hash.digest('hex').slice(0, 12);
  return `// GENERATED by scripts/gen-precache.mjs — do not edit by hand.\nself.__PRECACHE_VERSION = ${JSON.stringify(version)};\nself.__PRECACHE_FILES = ${JSON.stringify(['./', ...files.map((f) => './' + f)], null, 2)};\n`;
}

if (process.argv[1] && process.argv[1].endsWith('gen-precache.mjs')) {
  writeFileSync(join(root, 'precache.js'), buildPrecache());
  console.log('precache.js written');
}
